'use strict';
// brain find 自测：合成小库，验证中英检索、标题加权、frontmatter 只取 title/tags、点目录与附件目录跳过，
// 以及 2026-10-25 Astra 审查补的边界：CRLF/BOM、单字与扩展区汉字、读不了的根与文件、控制字符、UTF-16、软链、参数校验。
const fs = require('fs'); const path = require('path'); const os = require('os');
const { spawnSync } = require('child_process');
const { search, tokens, readText } = require('./find');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'brain-find-'));
const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'brain-find-out-'));
const put = (rel, text, enc) => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text, enc); };
put('_ai/memory/craft/WireGuard behind an upstream NAT- keepalives pin a stale mapping.md', '---\ntitle: x\nauthor_model: claude-opus-5-5\ncontributor_models:\n- gpt-6-astra\ntags:\n- wireguard\n---\nAfter a WAN re-dial the peer stays stuck because keepalives refresh the old NAT mapping.\n');
put('_ai/memory/journal/2026-09-10.md', '# 2026-09-10\n- NAS 与 Ubuntu 互传只有 118 MB/s，瓶颈在 vmbr0 的千兆上行，不是万兆网卡本身。\n- 员工名字 石嫄嫄 与 𠮷野 都是生僻字。\n');
put('_Private/清单-站点互联.md', '# 站点互联\nwg-site 两端：7 段与 8 段，DDNS 更新后客户端可能保留旧 endpoint。\n');
put('.obsidian/hidden.md', 'wireguard keepalive secret-ish noise\n');
put('_ai/library/assets/x/readme.md', 'wireguard asset noise\n');
put('crlf.md', '﻿---\r\ntitle: crlf page\r\nauthor_model: hiddenmodelqq\r\n---\r\nbody mentions crlfmarker here\r\n');
put('ctrl.md', 'ctrlmarker \u001b[31m red \u0007 bell\n');
put('utf16.md', Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from('utf16marker in a UTF-16 note\n', 'utf16le')]));
fs.writeFileSync(path.join(outside, 'secret.md'), 'symlinkleakmarker\n');
fs.symlinkSync(path.join(outside, 'secret.md'), path.join(root, 'link.md'));
fs.symlinkSync(outside, path.join(root, 'linkdir'));
put('locked.md', 'lockedmarker\n'); fs.chmodSync(path.join(root, 'locked.md'), 0o000);
let fails = 0; const ok = (c, m) => { console.log(`${c ? 'ok' : 'not ok'} - ${m}`); if (!c) fails++; };
const roots = [{ name: 'test', root }];
const run = q => search(roots, q, 9);
const top = q => (run(q).hits[0] || {}).path;
ok(top('wireguard keepalive stale') === '_ai/memory/craft/WireGuard behind an upstream NAT- keepalives pin a stale mapping.md', 'English keywords find the craft page by title and body');
ok(top('万兆 瓶颈 118') === '_ai/memory/journal/2026-09-10.md', 'Chinese bigrams find the journal line');
ok(top('DDNS endpoint 站点') === '_Private/清单-站点互联.md', 'inventory pages under the human layer are searched');
ok(run('claude-opus-5-5').hits.length === 0 && run('gpt-6-astra').hits.length === 0, 'frontmatter fields other than title/tags/aliases are ignored');
ok(!run('wireguard').hits.some(h => h.path.startsWith('.obsidian') || h.path.includes('/assets/')), 'dot-dirs and asset dirs are skipped');
ok(run('zzqqxxvv').hits.length === 0, 'no hits returns an empty list');
ok(tokens('万兆网卡').join(',') === '万兆,兆网,网卡', 'query CJK runs become bigrams only');
ok(top('名') === '_ai/memory/journal/2026-09-10.md', 'a single-character query matches inside a longer run');
ok(top('嫄') === '_ai/memory/journal/2026-09-10.md', 'a rare single character is found');
ok(top('𠮷') === '_ai/memory/journal/2026-09-10.md', 'supplementary-plane Han characters are tokenized');
ok(run('名').hits[0].lines.some(l => l.includes('名字')), 'single-character hits still return the matching line');
ok(top('crlfmarker') === 'crlf.md' && run('hiddenmodelqq').hits.length === 0, 'CRLF + BOM frontmatter is parsed and excluded fields stay hidden');
ok(top('utf16marker') === 'utf16.md', 'UTF-16LE notes with a BOM are decoded');
ok(run('ctrlmarker').hits[0].lines.every(l => !/[\u0000-\u0008\u001b\u007f]/.test(l)), 'terminal control characters are neutralised in snippets');
ok(run('symlinkleakmarker').hits.length === 0, 'symlinked files and directories are not followed');
const lockedRes = run('lockedmarker');
ok(lockedRes.hits.length === 0 && (process.getuid && process.getuid() === 0 ? true : lockedRes.stats.unreadable >= 1), 'unreadable files are counted, not silently treated as searched');
let threw = false; try { search([{ name: 'gone', root: path.join(root, 'no-such-dir') }], 'wireguard'); } catch { threw = true; }
ok(threw, 'a missing root throws instead of reporting no hits');
const cli = (args, env = {}) => spawnSync('node', [path.join(__dirname, 'find.js'), ...args], { encoding: 'utf8', env: { ...process.env, BRAIN_ROOT: root, ...env } });
ok(cli(['-n', 'oops', 'wireguard']).status === 2 && cli(['-n', '-3', 'wireguard']).status === 2, 'invalid -n is rejected');
ok(cli(['!!!']).status === 2, 'a query with no searchable tokens is rejected');
ok(cli(['wireguard'], { BRAIN_ROOT: path.join(root, 'no-such-dir') }).status === 1, 'CLI exits 1 when the root cannot be scanned');
ok(cli(['-n', '2', 'wireguard']).status === 0, 'valid CLI call succeeds');

// Astra 第二轮：长汉字串不能炸栈；读不了的子目录要计数；文件名里的控制字符要清洗；上级目录被换成软链要识破
put('long.md', 'longrunmarker ' + '汉'.repeat(130000) + '\n');
ok(top('longrunmarker') === 'long.md', 'a 130k-character Han run does not crash the search');
put('lockeddir/inner.md', 'lockeddirmarker\n'); fs.chmodSync(path.join(root, 'lockeddir'), 0o000);
const ld = run('lockeddirmarker');
ok(process.getuid && process.getuid() === 0 ? true : ld.stats.unreadableDirs >= 1, 'unreadable subdirectories are counted');
fs.chmodSync(path.join(root, 'lockeddir'), 0o700);
put('evil\u001b[31m.md', 'ansifilemarker\n');
const outAnsi = spawnSync('node', [path.join(__dirname, 'find.js'), 'ansifilemarker'], { encoding: 'utf8', env: { ...process.env, BRAIN_ROOT: root } }).stdout;
ok(outAnsi.includes('evil') && !/\u001b/.test(outAnsi), 'control characters in filenames are neutralised in output');
put('sub/race.md', 'innocent\n'); fs.writeFileSync(path.join(outside, 'race.md'), 'racemarker outside\n');
fs.renameSync(path.join(root, 'sub'), path.join(root, 'sub.real')); fs.symlinkSync(outside, path.join(root, 'sub'));
const rst = { unreadable: 0, truncated: 0, outside: 0 };
const raced = readText(path.join(root, 'sub', 'race.md'), rst, fs.realpathSync(root));
ok(raced === null && rst.outside === 1, 'a file reached through a swapped ancestor symlink is rejected');
fs.chmodSync(path.join(root, 'locked.md'), 0o600);
fs.rmSync(root, { recursive: true, force: true }); fs.rmSync(outside, { recursive: true, force: true });
console.log(fails ? `brain find: ${fails} failed` : 'brain find: all passed');
process.exit(fails ? 1 : 0);
