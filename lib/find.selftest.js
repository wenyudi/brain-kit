'use strict';
// brain find 自测：合成小库，验证中英检索、标题加权、frontmatter 只取 title/tags、点目录与附件目录跳过。
const fs = require('fs'); const path = require('path'); const os = require('os');
const { search, tokens } = require('./find');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'brain-find-'));
const put = (rel, text) => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text); };
put('_ai/memory/craft/WireGuard behind an upstream NAT- keepalives pin a stale mapping.md', '---\ntitle: x\nauthor_model: claude-opus-5-5\ncontributor_models:\n- gpt-6-astra\ntags:\n- wireguard\n---\nAfter a WAN re-dial the peer stays stuck because keepalives refresh the old NAT mapping.\n');
put('_ai/memory/journal/2026-09-10.md', '# 2026-09-10\n- NAS 与 Ubuntu 互传只有 118 MB/s，瓶颈在 vmbr0 的千兆上行，不是万兆网卡本身。\n');
put('_Private/清单-站点互联.md', '# 站点互联\nwg-site 两端：7 段与 8 段，DDNS 更新后客户端可能保留旧 endpoint。\n');
put('.obsidian/hidden.md', 'wireguard keepalive secret-ish noise\n');
put('_ai/library/assets/x/readme.md', 'wireguard asset noise\n');
let fails = 0; const ok = (c, m) => { console.log(`${c ? 'ok' : 'not ok'} - ${m}`); if (!c) fails++; };
const roots = [{ name: 'test', root }];
const top = q => (search(roots, q, 5).hits[0] || {}).path;
ok(top('wireguard keepalive stale') === '_ai/memory/craft/WireGuard behind an upstream NAT- keepalives pin a stale mapping.md', 'English keywords find the craft page by title and body');
ok(top('万兆 瓶颈 118') === '_ai/memory/journal/2026-09-10.md', 'Chinese bigrams find the journal line');
ok(top('DDNS endpoint 站点') === '_Private/清单-站点互联.md', 'inventory pages under the human layer are searched');
ok(search(roots, 'claude-opus-5-5', 5).hits.length === 0, 'frontmatter fields other than title/tags/aliases are ignored');
ok(search(roots, 'gpt-6-astra', 5).hits.length === 0, 'list items under other frontmatter keys are ignored');
ok(top('wireguard') && !search(roots, 'wireguard', 9).hits.some(h => h.path.startsWith('.obsidian') || h.path.includes('/assets/')), 'dot-dirs and asset dirs are skipped');
ok(search(roots, 'zzzz-nothing-here', 5).hits.length === 0, 'no hits returns an empty list');
ok(tokens('万兆网卡').join(',') === '万兆,兆网,网卡', 'CJK runs become character bigrams');
ok(search(roots, '万兆 瓶颈', 5).hits[0].lines.length > 0, 'hits carry matching lines');
fs.rmSync(root, { recursive: true, force: true });
console.log(fails ? `brain find: ${fails} failed` : 'brain find: all passed');
process.exit(fails ? 1 : 0);
